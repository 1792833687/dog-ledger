/**
 * 「清空全部数据」的判定。
 *
 * 为什么要有这一层：清空是**不可撤销**的，而且它删的是用户几个月记下来的账。
 * 所以加一道「你得亲手打出这两个字」的门槛 —— 它的作用不是防手滑（手滑点不到这里），
 * 是让人在打字的那两秒里想起来「我导出备份了吗」。
 *
 * 那两个字的文案从 `clearPhrase()` 一处来：按钮的禁用判定与弹窗正文的说明
 * 都念它，两处各写一遍迟早会对不上（改了正文忘了改判定，按钮就再也不亮了）。
 */

/** 要用户逐字打出来的那两个字。界面上的说明与判定都念它。 */
export function clearPhrase(): string {
  return '清空'
}

/**
 * 打出来的东西算不算数。
 *
 * 前后空格（含全角空格）用 `trim()` 抹掉：手机上打字、尤其是从别处粘贴时
 * 很容易带出空格，为这个把人卡在门外不值得。
 * 但**中间**的空格不抹 —— `'清 空'` 是三个字符，不是「清空」这两个字，
 * 真打错了的人应该看见按钮还是不亮，回头再看一眼。
 */
export function canClearData(input: string): boolean {
  return input.trim() === clearPhrase()
}
